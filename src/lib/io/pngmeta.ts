/** Utilidades de PNG sin dependencias del navegador. */
/** Añade el chunk pHYs (resolución) a un PNG para que los programas lo abran con el PPI correcto. */
export function pngWithDpi(png: Uint8Array, ppi: number): Uint8Array {
  // El PNG empieza con 8 bytes de firma + IHDR (25 bytes). Se inserta pHYs justo después.
  const at = 33;
  if (png.length < at || png[1] !== 0x50) return png;
  const ppm = Math.round(ppi / 0.0254);
  const chunk = new Uint8Array(21);
  const v = new DataView(chunk.buffer);
  v.setUint32(0, 9);
  chunk.set([0x70, 0x48, 0x59, 0x73], 4);
  v.setUint32(8, ppm);
  v.setUint32(12, ppm);
  chunk[16] = 1;
  v.setUint32(17, crc32(chunk.subarray(4, 17)));
  const out = new Uint8Array(png.length + chunk.length);
  out.set(png.subarray(0, at), 0);
  out.set(chunk, at);
  out.set(png.subarray(at), at + chunk.length);
  return out;
}

let crcTable: Uint32Array | null = null;
export function crc32(d: Uint8Array): number {
  if (!crcTable) {
    crcTable = new Uint32Array(256);
    for (let n = 0; n < 256; n++) {
      let c = n;
      for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
      crcTable[n] = c >>> 0;
    }
  }
  let c = 0xffffffff;
  for (let i = 0; i < d.length; i++) c = crcTable[(c ^ d[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

